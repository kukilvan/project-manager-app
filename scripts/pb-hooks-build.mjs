// Generates PocketBase's copy of the write semantics: src/domain/pbwrite.js → pb/pb_hooks/pm/pbwrite.js (ESM `export` turned into `module.exports`).
// Run after changing src/domain/pbwrite.js: `npm run pb:hooks`; `--check` writes nothing and exits 1 when the committed copy is stale.
// tests/pbwrite.test.js calls build() to fail on a stale copy (coding-standards rule 15). Reads and writes only these two files.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const SRC = 'src/domain/pbwrite.js';
export const OUT = 'pb/pb_hooks/pm/pbwrite.js';
const HEAD = '// GENERATED by scripts/pb-hooks-build.mjs — do not edit. Source: src/domain/pbwrite.js (coding-standards rule 15).';

// The CommonJS text for the source text; line endings are normalised to LF, so a CRLF checkout builds the same copy
export function build(source) {
  const text = source.replace(/\r\n/g, '\n');
  const names = [];
  const body = text.replace(/^export (function|const|let) ([A-Za-z_$][\w$]*)/gm, (_m, kw, name) => { names.push(name); return `${kw} ${name}`; });
  if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${SRC}: only "export function" and "export const" at the start of a line are supported`);
  return `${HEAD}\n${body.replace(/\n*$/, '\n')}\nmodule.exports = {\n${names.map((n) => `  ${n}: ${n},`).join('\n')}\n};\n`;
}

// true when the file on disk equals the built copy (ignoring CRLF of a Windows checkout)
export function isFresh(root = '.') {
  const want = build(fs.readFileSync(path.join(root, SRC), 'utf8'));
  let have = null;
  try { have = fs.readFileSync(path.join(root, OUT), 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
  return have === want;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (isFresh()) { console.log(`${OUT}: up to date`); process.exit(0); }
    console.error(`${OUT} is stale: run npm run pb:hooks`); process.exit(1);
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, build(fs.readFileSync(SRC, 'utf8')));
  console.log(`${OUT}: written`);
}
